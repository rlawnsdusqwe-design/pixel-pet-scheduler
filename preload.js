const { contextBridge, ipcRenderer } = require('electron');
const on = (ch) => (cb) => ipcRenderer.on(ch, (_e, v) => cb(v));
contextBridge.exposeInMainWorld('api', {
  getData: () => ipcRenderer.invoke('data:get'),
  saveEvents: (v) => ipcRenderer.invoke('events:save', v),
  saveTodos: (v) => ipcRenderer.invoke('todos:save', v),
  saveCharacter: (c) => ipcRenderer.invoke('character:save', c),
  saveMyChars: (l) => ipcRenderer.invoke('mychars:save', l),
  saveSettings: (s) => ipcRenderer.invoke('settings:save', s),
  action: (type, arg) => ipcRenderer.invoke('pet:action', type, arg),
  focus: (cmd) => ipcRenderer.invoke('focus:cmd', cmd),
  summary: () => ipcRenderer.invoke('pet:summary'),
  alarmCurrent: () => ipcRenderer.invoke('alarm:current'),
  alarmDismiss: () => ipcRenderer.send('alarm:dismiss'),
  alarmSnooze: (m) => ipcRenderer.send('alarm:snooze', m),
  alarmTest: () => ipcRenderer.send('alarm:test'),
  setIgnore: (v) => ipcRenderer.send('pet:ignore', v),
  dragStart: () => ipcRenderer.send('pet:dragStart'),
  dragMove: (p) => ipcRenderer.send('pet:dragMove', p),
  dragEnd: () => ipcRenderer.send('pet:dragEnd'),
  openPanel: (tab) => ipcRenderer.send('pet:openPanel', tab),
  petMenu: () => ipcRenderer.send('pet:menu'),
  hop: () => ipcRenderer.send('pet:hop'),
  widgetToggle: (k) => ipcRenderer.invoke('widget:toggle', k),
  widgetState: () => ipcRenderer.invoke('widget:state'),
  widgetSet: (k, patch) => ipcRenderer.invoke('widget:set', k, patch),
  widgetIgnore: (v) => ipcRenderer.send('widget:ignore', v),
  gameOpen: () => ipcRenderer.send('game:open'),
  gameClose: () => ipcRenderer.send('game:close'),
  onState: on('pet:state'), onBubble: on('pet:bubble'), onEmote: on('pet:emote'), onSound: on('pet:sound'), onGift: on('pet:gift'), onAct: on('pet:act'),
  onEvents: on('data:events'), onTodos: on('data:todos'), onCharacter: on('data:character'), onSettings: on('data:settings'),
  onPet: on('pet:data'), onFocus: on('focus:update'), onTab: on('panel:tab'), onWidgetCfg: on('widget:cfg'), onWidgets: on('widgets:changed'), onAlarm: on('alarm:update'),
});
